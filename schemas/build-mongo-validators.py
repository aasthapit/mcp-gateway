#!/usr/bin/env python3
"""Generate MongoDB $jsonSchema validators from the JSON Schema files in this directory.

The schema files are the single source of truth (draft-04 subset, so pydantic/ajv and
MongoDB can all consume them). MongoDB's ``$jsonSchema`` differs from draft-04 in a few
documented ways (https://www.mongodb.com/docs/manual/reference/operator/query/jsonSchema/),
which this script translates:

* ``$schema``, ``$id``, ``default``, ``examples`` and ``format`` are not accepted -> removed.
* ``{"type": "integer"}`` is not accepted -> ``{"bsonType": ["int", "long"]}``.
* ``{"type": "string", "format": "date-time"}`` -> ``{"bsonType": "date"}`` (stored as BSON Date).
* ``$ref``/``definitions`` are not supported -> the script refuses them.

Output: ``local/mongo-init/validators.js`` (a mongosh script, idempotent: creates each
collection or ``collMod``s an existing one).

Usage:
    python3 schemas/build-mongo-validators.py           # write the file
    python3 schemas/build-mongo-validators.py --check   # exit 1 if the file is stale (CI)
    python3 schemas/build-mongo-validators.py --validate-seed  # check local/seed/*.json
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / "local" / "mongo-init" / "validators.js"
SEED_DIR = ROOT / "local" / "seed"

# collection name -> schema file
COLLECTIONS: dict[str, str] = {
    "upstreams": "upstreams.schema.json",
    "toolsets": "toolsets.schema.json",
    "grants": "grants.schema.json",
    "meta": "meta.schema.json",
}

DROP_KEYS = {"$schema", "$id", "default", "examples"}
UNSUPPORTED = {"$ref", "definitions", "$defs"}


def to_mongo(node: Any) -> Any:
    """Recursively translate a draft-04 schema node into a MongoDB $jsonSchema node."""
    if isinstance(node, list):
        return [to_mongo(n) for n in node]
    if not isinstance(node, dict):
        return node

    for key in UNSUPPORTED:
        if key in node:
            raise SystemExit(f"error: `{key}` is not supported by MongoDB $jsonSchema")

    out: dict[str, Any] = {}
    fmt = node.get("format")
    for key, value in node.items():
        if key in DROP_KEYS or key == "format":
            continue
        if key == "type":
            if value == "integer":
                out["bsonType"] = ["int", "long"]
                continue
            if value == "string" and fmt == "date-time":
                out["bsonType"] = "date"
                continue
            if isinstance(value, list) and ("integer" in value or fmt == "date-time"):
                raise SystemExit("error: type unions with integer/date-time are not translated")
            out["type"] = value
            continue
        if key in ("properties", "patternProperties"):
            out[key] = {k: to_mongo(v) for k, v in value.items()}
            continue
        if key in ("items", "additionalProperties", "not") and isinstance(value, dict):
            out[key] = to_mongo(value)
            continue
        if key in ("anyOf", "oneOf", "allOf"):
            out[key] = [to_mongo(v) for v in value]
            continue
        out[key] = copy.deepcopy(value)
    return out


def load_schema(name: str) -> dict[str, Any]:
    with (HERE / name).open(encoding="utf-8") as fh:
        return json.load(fh)


def render() -> str:
    lines = [
        "// GENERATED by schemas/build-mongo-validators.py -- do not edit by hand.",
        "// Applies $jsonSchema validators to the policy collections. Idempotent.",
        '// Run with: mongosh "$MONGO_URI" local/mongo-init/validators.js',
        "",
        "(() => {",
        '  const dbName = process.env.MONGO_DB || "mcp_gateway";',
        "  const policyDb = db.getSiblingDB(dbName);",
        "  const validators = ",
    ]
    validators = {coll: to_mongo(load_schema(file)) for coll, file in COLLECTIONS.items()}
    body = json.dumps(validators, indent=2, sort_keys=True)
    body = "\n".join("  " + line for line in body.splitlines())
    lines[-1] += body.lstrip() + ";"
    lines += [
        "",
        "  const existing = new Set(policyDb.getCollectionNames());",
        "  for (const [name, schema] of Object.entries(validators)) {",
        "    const options = {",
        "      validator: { $jsonSchema: schema },",
        '      validationLevel: "strict",',
        '      validationAction: "error",',
        "    };",
        "    if (existing.has(name)) {",
        "      policyDb.runCommand({ collMod: name, ...options });",
        "      print(`collMod ${dbName}.${name}`);",
        "    } else {",
        "      policyDb.createCollection(name, options);",
        "      print(`createCollection ${dbName}.${name}`);",
        "    }",
        "  }",
        "",
        "  // Indexes used by the gateway's snapshot loader and the admin API.",
        '  policyDb.grants.createIndex({ enabled: 1, priority: 1 }, { name: "enabled_priority" });',
        '  policyDb.toolsets.createIndex({ enabled: 1 }, { name: "enabled" });',
        '  policyDb.upstreams.createIndex({ enabled: 1 }, { name: "enabled" });',
        '  policyDb.policy_history.createIndex({ at: -1 }, { name: "at_desc" });',
        '  print("validators applied");',
        "})();",
        "",
    ]
    return "\n".join(lines)


def validate_seed() -> int:
    try:
        import jsonschema
    except ImportError:
        print("error: --validate-seed needs the `jsonschema` package (pip install jsonschema)")
        return 2
    failures = 0
    for coll, file in COLLECTIONS.items():
        seed = SEED_DIR / f"{coll}.json"
        if not seed.exists():
            continue
        schema = load_schema(file)
        validator = jsonschema.Draft4Validator(
            schema, format_checker=jsonschema.Draft4Validator.FORMAT_CHECKER
        )
        with seed.open(encoding="utf-8") as fh:
            docs = json.load(fh)
        docs = docs if isinstance(docs, list) else [docs]
        for doc in docs:
            errors = sorted(validator.iter_errors(doc), key=lambda e: list(e.path))
            for err in errors:
                failures += 1
                path = "/".join(str(p) for p in err.path) or "<root>"
                print(f"{seed.relative_to(ROOT)} {doc.get('_id')!r} {path}: {err.message}")
        print(f"ok: {seed.relative_to(ROOT)} ({len(docs)} documents) against {file}")
    return 1 if failures else 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the output is stale")
    parser.add_argument("--validate-seed", action="store_true", help="validate local/seed/*.json")
    args = parser.parse_args(argv)

    rendered = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(f"error: {OUT.relative_to(ROOT)} is stale; run `make validators`")
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} is up to date")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")

    if args.validate_seed:
        return validate_seed()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
